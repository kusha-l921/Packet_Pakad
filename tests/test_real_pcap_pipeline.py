@register_test
def test_daemon_directory_scan_ingestion():
    """Verify Method A: Directory scanning for X.509 certs and attachment to session."""
    with tempfile.TemporaryDirectory() as td:
        cert_dir = Path(td)
        leaf_pem = _generate_test_cert_pem("gateway.testbed.internal", is_ca=False)
        (cert_dir / "gateway.crt").write_bytes(leaf_pem)

        pipe = IntegratedPipeline(output_dir=Path(td) / "out")
        spi = "0x1122334455667788"
        pipe.aggregator.ingest_packet({
            "common": {"initiator_spi": spi, "plane": "control", "exchange_type": 34},
            "IKE_SA_INIT": {"exchange": "IKE_SA_INIT", "proposals": []},
            "IKE_AUTH": {"exchange": "IKE_AUTH"}
        })

        success = pipe.ingest_daemon_credentials_from_path(
            initiator_spi=spi,
            cert_dir=cert_dir,
            identity_value="gateway.testbed.internal",
        )
        assert success is True

        canon = pipe.aggregator.get_canonical_session_dict(spi)
        assert "auth_metadata" in canon
        assert canon["auth_metadata"]["source"] == "directory_scan"
        certs = canon["auth_metadata"]["responder"]["certificates"]
        assert len(certs) == 1
        assert "gateway.testbed.internal" in certs[0].get("san", [])


@register_test
def test_daemon_webhook_rest_api_ingestion():
    """Verify Section 4: REST API & Daemon Webhook server integration."""
    with tempfile.TemporaryDirectory() as td:
        pipe = IntegratedPipeline(output_dir=Path(td))
        port = 8991
        server = DaemonApiServer(
            host="127.0.0.1",
            port=port,
            pipeline=pipe,
            vici_socket_path=str(_VICI_SOCKET) if _VICI_SOCKET.exists() else None,
        )
        server.start_background()
        time.sleep(0.3)

        try:
            # 1. Health check
            req = urllib.request.urlopen(f"http://127.0.0.1:{port}/health")
            health = json.loads(req.read().decode())
            assert health.get("status") == "healthy"

            # 2. Ingest real PCAP via API
            pcap_file = _DATASET_DIR / "T003" / "capture.pcap"
            pcap_req = urllib.request.Request(
                f"http://127.0.0.1:{port}/api/v1/pcap",
                data=json.dumps({"pcap_path": str(pcap_file)}).encode(),
                headers={"Content-Type": "application/json"}
            )
            pcap_res = json.loads(urllib.request.urlopen(pcap_req).read().decode())
            assert pcap_res.get("status") == "success"
            spi = pcap_res["completed_sessions"][0]

            # 3. Post daemon credentials via webhook
            cred_payload = {
                "source": "daemon_webhook_test",
                "daemon_type": "strongswan",
                "responder": {
                    "identity": {"type": 2, "value": "vpn-gw.internal"},
                    "auth_method": 14,
                    "certificates": []
                }
            }
            cred_req = urllib.request.Request(
                f"http://127.0.0.1:{port}/api/v1/sessions/{spi}/credentials",
                data=json.dumps(cred_payload).encode(),
                headers={"Content-Type": "application/json"}
            )
            cred_res = json.loads(urllib.request.urlopen(cred_req).read().decode())
            assert cred_res.get("status") == "attached"

            # 4. Query session through REST API
            sess_req = urllib.request.urlopen(f"http://127.0.0.1:{port}/api/v1/sessions/{spi}")
            sess_res = json.loads(sess_req.read().decode())
            assert sess_res.get("session_id") == spi
            assert "canonical_session" in sess_res
            assert "rfc_compliance" in sess_res
        finally:
            server.stop()


def run_all():
    global _passed, _failed
    print("=" * 80)
    print("RUNNING REAL PCAP & DAEMON API PIPELINE TEST SUITE")
    print("=" * 80)
    for fn in _tests:
        try:
            fn()
            _passed += 1
            print(f"  PASS  {fn.__name__}")
        except AssertionError as e:
            _failed += 1
            print(f"  FAIL  {fn.__name__} -> {e}")
        except Exception as e:
            _failed += 1
            print(f"  FAIL  {fn.__name__} -> EXCEPTION: {e}")
    print("=" * 80)
    print(f"RESULTS: {_passed} passed, {_failed} failed, {_passed + _failed} total")
    print("=" * 80)
    return _failed == 0


if __name__ == "__main__":
    sys.exit(0 if run_all() else 1)
