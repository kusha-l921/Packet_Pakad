@register_test
def test_real_pcap_t003_tunnel_aes_gcm():
    """Verify T003 real capture: AES-256-GCM, DH-14 (MODP-2048), SHA-256, ESP telemetry."""
    pcap_path = _DATASET_DIR / "T003" / "capture.pcap"
    assert pcap_path.is_file(), f"T003 PCAP not found at {pcap_path}"

    with tempfile.TemporaryDirectory() as td:
        out_dir = Path(td)
        pipe = IntegratedPipeline(output_dir=out_dir, auto_export_on_complete=True)
        completed = pipe.process_pcap(pcap_path)

        assert len(completed) >= 1, f"Expected at least 1 completed session, got {completed}"
        spi = completed[0]
        assert spi == "0xbcefbfeb6dcb6f59", f"Unexpected initiator SPI: {spi}"

        session = pipe.aggregator.get_session(spi)
        assert session is not None
        assert session.is_handshake_complete() is True

        # Verify negotiated crypto transforms from real wire proposals
        canon = pipe.aggregator.get_canonical_session_dict(spi)
        props = canon.get("IKE_SA_INIT", {}).get("proposals", [])
        assert len(props) > 0, "No proposals in canonical session"
        transforms = props[0].get("transforms", {})

        enc_transforms = transforms.get("encryption", [])
        assert any(t.get("id") == 20 for t in enc_transforms), "AES-GCM (transform id 20) not found"

        dh_transforms = transforms.get("dh_group", [])
        assert any(t.get("id") == 14 for t in dh_transforms), "MODP-2048 (DH group 14) not found"

        # Verify ESP data plane traffic was captured and processed
        assert len(pipe.latest_flow_verdicts) >= 1, "Flow engine did not record any flow verdicts"

        # Verify exported report artifacts exist
        session_out = out_dir / "sessions" / spi
        assert (session_out / "intermediate_canonical_session.json").is_file()
        assert (session_out / "rfc_compliance_report.json").is_file()
        assert (session_out / "crypto_vector_posture.json").is_file()
        assert (session_out / "unified_rag_payload.json").is_file()

        # Validate unified RAG contents
        with open(session_out / "unified_rag_payload.json") as f:
            rag = json.load(f)
        assert rag.get("session_id") == spi
        assert "cryptographic_posture" in rag.get("summaries", {})
        assert "rfc_compliance" in rag.get("summaries", {})


