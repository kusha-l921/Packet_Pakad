def load_env_file(env_path: Path | None = None) -> None:
    """Manually parse .env file if present without requiring external libraries."""
    target = env_path or (Path.cwd() / ".env")
    if not target.is_file():
        return
    try:
        with open(target, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip().strip("'\"")
                if k and k not in os.environ:
                    os.environ[k] = v
        logger.debug("Loaded environment variables from %s", target)
    except Exception as e:
        logger.warning("Could not read .env file: %s", e)


def sanitize_payload(val: Any) -> Any:
    """Recursively scrub any sensitive cryptographic private key material."""
    if isinstance(val, str):
        for token in SENSITIVE_KEY_SUBSTRINGS:
            if token in val:
                return "[REDACTED_SENSITIVE_KEY_MATERIAL]"
        return val
    elif isinstance(val, dict):
        return {k: sanitize_payload(v) for k, v in val.items()}
    elif isinstance(val, list):
        return [sanitize_payload(item) for item in val]
    return val


def discover_session_files(output_dir: Path, session_id: str | None = None) -> dict[str, Path | None]:
    """Locate all expected JSON files in output_dir or output_dir/sessions/<session_id>."""
    target_dir = output_dir
    if session_id:
        sess_path = output_dir / "sessions" / session_id
        if sess_path.is_dir():
            target_dir = sess_path
        elif (output_dir / session_id).is_dir():
            target_dir = output_dir / session_id

    discovered: dict[str, Path | None] = {}
    for key, fname in EXPECTED_FILENAMES.items():
        direct = target_dir / fname
        if direct.is_file():
            discovered[key] = direct
        else:
            # Check recursively in subdirectories
            matches = list(target_dir.glob(f"**/{fname}"))
            discovered[key] = matches[0] if matches else None

    return discovered


def load_all_session_data(output_dir: Path, session_id: str | None = None) -> dict[str, Any]:
    """Ingest, validate, and sanitize all JSON testing outputs."""
    discovered = discover_session_files(output_dir, session_id)
    loaded_data: dict[str, Any] = {}
    file_metadata: list[dict[str, Any]] = []

    for key, path in discovered.items():
        if path and path.is_file():
            try:
                with open(path, "r", encoding="utf-8") as f:
                    raw_content = json.load(f)
                clean_content = sanitize_payload(raw_content)
                loaded_data[key] = clean_content
                file_metadata.append({
                    "role": key,
                    "filename": path.name,
                    "filepath": str(path.resolve()),
                    "size_bytes": path.stat().st_size,
                })
            except Exception as e:
                logger.error("Failed to parse JSON file %s: %s", path, e)
                loaded_data[key] = None
        else:
            loaded_data[key] = None

    # Discover any additional custom JSON files in output_dir
    extra_jsons: dict[str, Any] = {}
    target_dir = output_dir / "sessions" / session_id if session_id else output_dir
    if target_dir.is_dir():
        for p in target_dir.glob("*.json"):
            if p.name not in EXPECTED_FILENAMES.values():
                try:
                    with open(p, "r", encoding="utf-8") as f:
                        extra_jsons[p.stem] = sanitize_payload(json.load(f))
                except Exception:
                    pass

    return {
        "loaded_data": loaded_data,
        "extra_jsons": extra_jsons,
        "file_metadata": file_metadata,
        "target_dir": str(target_dir.resolve()),
    }


def extract_executive_metrics(loaded: dict[str, Any]) -> dict[str, Any]:
    """Synthesize high-level structured metrics for the report and dashboard cards."""
    canon = loaded.get("canonical_session") or {}
    rfc = loaded.get("rfc_compliance") or {}
    vec = loaded.get("vector_posture") or {}
    cert = loaded.get("cert_health") or {}
    flow = loaded.get("traffic_flow") or {}
    rag = loaded.get("unified_rag") or {}

    # Extract session identity
    session_id = (
        canon.get("session_id")
        or rag.get("session_id")
        or (canon.get("common", {}).get("initiator_spi"))
        or rfc.get("session_id", "UNKNOWN_SESSION")
    )

    common = canon.get("common", {})
    endpoints = common.get("endpoints", {})
    src_ip = endpoints.get("initiator_ip") or common.get("src_ip", "N/A")
    dst_ip = endpoints.get("responder_ip") or common.get("dst_ip", "N/A")
    ike_version = common.get("ike_version") or common.get("protocol_version", 2)
    ipsec_mode = canon.get("ipsec_mode") or rfc.get("ipsec_mode", "TUNNEL")

    # RFC Compliance Metrics
    rfc_status = rfc.get("overall_rfc_status", "UNKNOWN")
    pqc_class = rfc.get("pqc_classification", "UNKNOWN")
    hybrid_class = rfc.get("hybrid_classification", "UNKNOWN")
    crypto_posture = rfc.get("cryptographic_posture", "UNKNOWN")
    counts = rfc.get("counts", {})
    passed_rules = counts.get("passed_rules", rfc.get("passed_rules_count", 0))
    failed_rules = counts.get("critical_failures", rfc.get("critical_failures_count", 0))
    warning_rules = counts.get("warnings", rfc.get("warnings_count", 0))
    total_evaluated = counts.get("total_evaluated", passed_rules + failed_rules + warning_rules)

    # 19-D Cryptographic Vector Metrics
    best_anchor = vec.get("best_match", "N/A")
    anchor_display = vec.get("display_name", best_anchor)
    similarity_score = vec.get("best_score", 0.0)
    cosine_distance = vec.get("best_distance", 0.0)
    similarity_pct = f"{similarity_score * 100:.2f}%" if similarity_score else "N/A"
    rankings = vec.get("rankings", [])

    # PKI Certificate Metrics
    cert_status = cert.get("overall_health_status", "UNKNOWN")
    cert_compliant = cert.get("is_compliant", True)
    peers = cert.get("peers") or cert.get("peer_audits", {})
    total_certs = cert.get("summary", {}).get("total_certificates_audited", len(peers))

    # Traffic Flow Metrics
    flow_features = flow.get("features", {})
    packet_count = flow.get("packet_count") or flow_features.get("total_packets", 0)
    total_bytes = flow_features.get("total_bytes", 0)
    mean_pkt_size = flow_features.get("mean_packet_size", 0)
    flow_verdict = flow.get("verdict", "NOMINAL")

    # Preliminary Risk Score Heuristic (0 to 100)
    base_risk = 0.0
    if rfc_status == "FAIL":
        base_risk += 40.0
    elif rfc_status == "WARNING":
        base_risk += 15.0

    if failed_rules > 0:
        base_risk += min(30.0, failed_rules * 10.0)
    if warning_rules > 0:
        base_risk += min(15.0, warning_rules * 5.0)

    if cert_status in ("EXPIRED", "CRITICAL", "REVOKED"):
        base_risk += 35.0
    elif not cert_compliant:
        base_risk += 20.0

    if best_anchor in ("NIST_SP800_131A_DEPRECATED", "LEGACY_BROKEN"):
        base_risk += 35.0
    elif best_anchor == "RFC8247_CLASSICAL_BASELINE":
        base_risk += 15.0

    calculated_risk = max(5.0, min(95.0, base_risk)) if (failed_rules > 0 or not cert_compliant) else (
        12.0 if best_anchor == "NIST_PQC_TRANSITIONAL" else 8.0 if best_anchor == "CNSA_2_0" else 22.0
    )

    return {
        "session_id": session_id,
        "src_ip": src_ip,
        "dst_ip": dst_ip,
        "ike_version": ike_version,
        "ipsec_mode": ipsec_mode,
        "rfc_status": rfc_status,
        "pqc_class": pqc_class,
        "hybrid_class": hybrid_class,
        "crypto_posture": crypto_posture,
        "passed_rules": passed_rules,
        "failed_rules": failed_rules,
        "warning_rules": warning_rules,
        "total_evaluated": total_evaluated,
        "best_anchor": best_anchor,
        "anchor_display": anchor_display,
        "similarity_score": similarity_score,
        "similarity_pct": similarity_pct,
        "cosine_distance": cosine_distance,
        "rankings": rankings,
        "cert_status": cert_status,
        "cert_compliant": cert_compliant,
        "total_certs": total_certs,
        "peers": peers,
        "packet_count": packet_count,
        "total_bytes": total_bytes,
        "mean_pkt_size": mean_pkt_size,
        "flow_verdict": flow_verdict,
        "estimated_risk_score": calculated_risk,
    }


def prepare_context_payload(loaded: dict[str, Any], compact: bool = False) -> dict[str, Any]:
    """Condense or serialize JSON outputs to optimize token budget while retaining 100% analytical fidelity."""
    if not compact:
        full_payload = {}
        for k in ["canonical_session", "rfc_compliance", "vector_posture", "cert_health", "traffic_flow"]:
            if loaded.get(k):
                full_payload[k] = loaded[k]
        return full_payload

    # Compact mode: summarize passed rules while preserving critical failures, warnings, certs, and vectors
    compact_payload: dict[str, Any] = {}

    # 1. Canonical Session
    canon = loaded.get("canonical_session")
    if canon:
        compact_payload["canonical_session"] = {
            "session_id": canon.get("session_id"),
            "ipsec_mode": canon.get("ipsec_mode"),
            "common": canon.get("common"),
            "IKE_SA_INIT_transforms": [
                p.get("transforms") for p in canon.get("IKE_SA_INIT", {}).get("proposals", [])
            ],
            "IKE_AUTH": canon.get("IKE_AUTH"),
        }

    # 2. RFC Compliance (preserve all failures, warnings, categories, and rule summaries)
    rfc = loaded.get("rfc_compliance")
    if rfc:
        compact_payload["rfc_compliance"] = {
            "overall_rfc_status": rfc.get("overall_rfc_status"),
            "pqc_classification": rfc.get("pqc_classification"),
            "hybrid_classification": rfc.get("hybrid_classification"),
            "cryptographic_posture": rfc.get("cryptographic_posture"),
            "counts": rfc.get("counts"),
            "category_summaries": rfc.get("category_summaries"),
            "critical_failures": rfc.get("critical_failures", []),
            "warnings": rfc.get("warnings", []),
            "not_verifiable_rules": rfc.get("not_verifiable_rules", []),
            "passed_rules_overview": [
                {"rule_id": r.get("rule_id"), "condition": r.get("condition")}
                for r in rfc.get("passed_rules", [])[:15]
            ],
        }

    # 3. Vector Posture
    if loaded.get("vector_posture"):
        compact_payload["vector_posture"] = loaded["vector_posture"]

    # 4. PKI Health
    cert = loaded.get("cert_health")
    if cert:
        compact_payload["cert_health"] = {
            "overall_health_status": cert.get("overall_health_status"),
            "is_compliant": cert.get("is_compliant"),
            "summary": cert.get("summary"),
            "peers": cert.get("peers") or cert.get("peer_audits"),
            "findings": cert.get("findings", []),
            "remediation_actions": cert.get("remediation_actions", []),
        }

    # 5. Traffic Flow
    if loaded.get("traffic_flow"):
        compact_payload["traffic_flow"] = loaded["traffic_flow"]

    return compact_payload


