def main() -> None:
    parser = argparse.ArgumentParser(
        description="Autonomous AI Security & Compliance Report Generator (Groq LLM + Enterprise Rule Engine)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "-k", "--api-key",
        dest="api_key",
        help="Groq API Key (or set GROQ_API_KEY environment variable)",
        default=None,
    )
    parser.add_argument(
        "-o", "--output-dir",
        dest="output_dir",
        help="Path to testing output directory containing engine JSONs",
        default="output",
    )
    parser.add_argument(
        "-s", "--session-id",
        dest="session_id",
        help="Specific session ID or SPI subfolder to audit (optional)",
        default=None,
    )
    parser.add_argument(
        "-r", "--report-dir",
        dest="report_dir",
        help="Directory where generated reports are persisted",
        default="report",
    )
    parser.add_argument(
        "-m", "--model",
        dest="model",
        help="Groq LLM model identifier",
        default="llama-3.3-70b-versatile",
    )
    parser.add_argument(
        "--format",
        dest="format",
        choices=["both", "markdown", "html"],
        help="Output format to persist",
        default="both",
    )
    parser.add_argument(
        "--compact",
        dest="compact",
        action="store_true",
        help="Force high-density compact JSON context to preserve token limits",
    )
    parser.add_argument(
        "--dry-run",
        dest="dry_run",
        action="store_true",
        help="Run offline mock simulation and generate report without calling Groq API",
    )
    parser.add_argument(
        "-v", "--verbose",
        dest="verbose",
        action="store_true",
        help="Enable verbose diagnostic logging",
    )

    args = parser.parse_args()

    # Load environment variables (.env file support)
    load_env_file()

    output_dir = Path(args.output_dir)
    report_dir = Path(args.report_dir)
    report_dir.mkdir(parents=True, exist_ok=True)

    print(colored("=" * 72, "cyan"))
    print(colored("  ENTERPRISE IPSEC & IKEV2 SECURITY AUDIT REPORT GENERATOR", "cyan", attrs=["bold"]))
    print(colored("=" * 72, "cyan"))
    print(f"[*] Scanning output directory: {output_dir.resolve()}")
    if args.session_id:
        print(f"[*] Target Session Filter:    {args.session_id}")
    print(f"[*] Target Groq Model:        {args.model if not args.dry_run else 'OFFLINE (Dry-Run)'}")

    # Discover and load all session artifacts
    session_data = load_all_session_data(output_dir, args.session_id)
    loaded = session_data["loaded_data"]
    file_metadata = session_data["file_metadata"]

    loaded_count = len([k for k, v in loaded.items() if v is not None])
    if loaded_count == 0:
        print(colored(f"\n[ERROR] No valid test JSON reports were found in '{output_dir}'.", "red"))
        print("Please run the testing pipeline or tests to generate session artifacts before generating a report.")
        sys.exit(1)

    print(colored(f"[+] Discovered and ingested {loaded_count} analytical JSON source(s):", "green"))
    for f in file_metadata:
        print(f"    - {f['role']:<18} : {f['filename']} ({f['size_bytes']:,} bytes)")

    # Extract high-level metrics
    metrics = extract_executive_metrics(loaded)
    print(f"[*] Identified Session SPI:   {metrics['session_id']}")
    print(f"[*] Cryptographic Posture:    {metrics['crypto_posture']} (Anchor: {metrics['best_anchor']})")
    print(f"[*] RFC Compliance Status:    {metrics['rfc_status']} (Passed: {metrics['passed_rules']}, Failures: {metrics['failed_rules']})")

    report_markdown = ""

    if args.dry_run:
        print(colored("\n[*] DRY-RUN MODE: Generating synthetic audit report from active metrics...", "yellow"))
        report_markdown = generate_mock_report(metrics)
    else:
        # Resolve API Key
        api_key = args.api_key or os.environ.get("GROQ_API_KEY")
        if not api_key:
            print(colored("\n[!] Groq API Key was not provided via CLI flag or GROQ_API_KEY environment variable.", "yellow"))
            try:
                api_key = input("Enter your Groq API Key: ").strip()
            except (KeyboardInterrupt, EOFError):
                print("\nAborted.")
                sys.exit(1)

        if not api_key:
            print(colored("\n[ERROR] A valid Groq API key is required to generate the report.", "red"))
            print("Please provide it via one of the following methods:")
            print("  1. CLI parameter:    python generate_report.py --api-key gsk_...")
            print("  2. Environment var:  $env:GROQ_API_KEY='gsk_...' (PowerShell) or export GROQ_API_KEY='gsk_...'")
            print("  3. .env file:        Add GROQ_API_KEY=gsk_... to a .env file in the workspace root")
            print("  4. Dry-run test:     python generate_report.py --dry-run")
            sys.exit(1)

        print("\n[*] Assembling comprehensive prompt context with empirical session metrics...")
        system_prompt, user_prompt = build_groq_prompts(loaded, metrics, file_metadata, compact=args.compact)

        print(f"[*] Connecting to Groq Cloud API ({args.model})...")
        client = Groq(api_key=api_key)

        t0 = time.time()
        completion = None

        # Attempt call with primary model and prompt
        try:
            completion = client.chat.completions.create(
                model=args.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.2,
                max_tokens=8192,
            )
        except Exception as e:
            err_msg = str(e)
            logger.warning("Primary attempt failed: %s", err_msg)

            # Check if rate-limited or TPM exceeded; auto-switch to compact prompt
            if ("rate_limit" in err_msg.lower() or "tpm" in err_msg.lower() or "tokens" in err_msg.lower()) and not args.compact:
                print(colored("[!] Rate limit / TPM limit detected. Retrying with high-density compact payload...", "yellow"))
                sys_p_compact, usr_p_compact = build_groq_prompts(loaded, metrics, file_metadata, compact=True)
                try:
                    completion = client.chat.completions.create(
                        model=args.model,
                        messages=[
                            {"role": "system", "content": sys_p_compact},
                            {"role": "user", "content": usr_p_compact},
                        ],
                        temperature=0.2,
                        max_tokens=8192,
                    )
                except Exception as ce:
                    logger.error("Compact payload retry failed: %s", ce)

            # Fallback models if primary model still failed
            if completion is None:
                fallback_models = ["llama-3.1-70b-versatile", "llama-3.1-8b-instant"]
                for fallback in fallback_models:
                    if fallback == args.model:
                        continue
                    print(colored(f"[!] Retrying with fallback model: {fallback}...", "yellow"))
                    try:
                        sys_p_fb, usr_p_fb = build_groq_prompts(loaded, metrics, file_metadata, compact=True)
                        completion = client.chat.completions.create(
                            model=fallback,
                            messages=[
                                {"role": "system", "content": sys_p_fb},
                                {"role": "user", "content": usr_p_fb},
                            ],
                            temperature=0.2,
                            max_tokens=8192,
                        )
                        args.model = fallback
                        break
                    except Exception as fe:
                        logger.error("Fallback to %s failed: %s", fallback, fe)

        if completion is None:
            print(colored("\n[FATAL] Unable to complete LLM synthesis via Groq. Please verify API key and rate limits.", "red"))
            sys.exit(1)

        duration = time.time() - t0
        report_markdown = completion.choices[0].message.content or ""
        prompt_tokens = getattr(completion.usage, "prompt_tokens", "N/A")
        completion_tokens = getattr(completion.usage, "completion_tokens", "N/A")
        total_tokens = getattr(completion.usage, "total_tokens", "N/A")
        print(colored(f"[+] Synthesis complete in {duration:.2f}s! Tokens: {total_tokens} (prompt: {prompt_tokens}, completion: {completion_tokens})", "green"))

    # Generate timestamped filenames
    timestamp_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    clean_session = re.sub(r"[^a-zA-Z0-9_-]", "_", str(metrics['session_id']))
    base_name = f"security_audit_report_{clean_session}_{timestamp_str}"
    
    report_title = f"IKEv2 / IPsec Cryptographic Audit & Compliance Evaluation"
    generation_timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC+05:30")

    saved_files: list[Path] = []

    # 1. Save Markdown Report
    if args.format in ("both", "markdown"):
        md_file = report_dir / f"{base_name}.md"
        with open(md_file, "w", encoding="utf-8") as f:
            f.write(report_markdown)
        saved_files.append(md_file)

        # Update pointer to latest markdown report
        latest_md = report_dir / "latest_report.md"
        with open(latest_md, "w", encoding="utf-8") as f:
            f.write(report_markdown)

    # 2. Save Standalone HTML Report
    if args.format in ("both", "html"):
        html_file = report_dir / f"{base_name}.html"
        html_content = generate_html_report(
            markdown_content=report_markdown,
            metrics=metrics,
            report_title=report_title,
            generation_time=generation_timestamp,
            model_name=args.model if not args.dry_run else "Offline Simulator",
        )
        with open(html_file, "w", encoding="utf-8") as f:
            f.write(html_content)
        saved_files.append(html_file)

        # Update pointer to latest HTML report
        latest_html = report_dir / "latest_report.html"
        with open(latest_html, "w", encoding="utf-8") as f:
            f.write(html_content)

    print(colored("\n" + "=" * 72, "green"))
    print(colored("  REPORT GENERATION SUCCESSFUL!", "green", attrs=["bold"]))
    print(colored("=" * 72, "green"))
    for sf in saved_files:
        print(f"  [>] {sf.resolve()}")
    if args.format in ("both", "html"):
        print(f"  [>] Open interactive dashboard: {(report_dir / 'latest_report.html').resolve()}")
    print("=" * 72 + "\n")


if __name__ == "__main__":
    main()
